import type { FoodItem, PlannerFood } from '@bharatbite/core';
import catalogJson from '@bharatbite/foods/generated/catalog.compact.json';
import plannerPoolJson from '@bharatbite/foods/generated/planner-pool.json';

/**
 * The catalog is compiled into the application bundle, not read from disk.
 *
 * A serverless function has no `packages/foods/data` directory and its working
 * directory is not the repository, so `readFileSync` at request time fails. The
 * generated JSON is imported statically and therefore shipped with the bundle.
 * Search, portion maths and planning keep working when Postgres is slow or the
 * phone is offline, which is the point of bundling it at all.
 */
interface CatalogFile {
  schemaVersion: number;
  generatedAt: string;
  stats: {
    ingredients: number;
    compositeDishes: number;
    directFoods: number;
    totalFoods: number;
    totalVariants: number;
    totalAliases: number;
    sourceVerified: number;
    calculated: number;
    needsAudit: number;
    warnings: number;
  };
  foods: FoodItem[];
}

const catalog = catalogJson as unknown as CatalogFile;

const foods: readonly FoodItem[] = catalog.foods;

export function getBundledFoods(): readonly FoodItem[] {
  return foods;
}

export function catalogStats() {
  return catalog.stats;
}

export function catalogGeneratedAt(): string {
  return catalog.generatedAt;
}

/**
 * Pre-computed planner pool (one row per plannable preparation). Generated by
 * `npm run seed:generate` from the same catalog, so the planner never has to
 * rebuild it at request time.
 */
export function getPlannerPool(): readonly PlannerFood[] {
  return plannerPoolJson as unknown as PlannerFood[];
}
